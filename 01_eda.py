# ============================================================
# 7. Operator Measurement Error Analysis
# ============================================================

# Calculate measurement error in MSA dataset
msa["error_nm"] = (
    msa["measured_cd_nm"]
    - msa["true_cd_nm"]
)

msa["absolute_error_nm"] = (
    msa["error_nm"].abs()
)

# Summarize measurement error by operator
operator_summary = (
    msa.groupby("operator_id")
    .agg(
        mean_error=("error_nm", "mean"),
        std_error=("error_nm", "std"),
        MAE=("absolute_error_nm", "mean"),
        count=("error_nm", "count")
    )
    .round(4)
)

print("\n" + "=" * 60)
print("OPERATOR MEASUREMENT ERROR SUMMARY")
print("=" * 60)

print(operator_summary)


# ============================================================
