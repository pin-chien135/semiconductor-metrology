# ============================================================
# 6. Measurement Error Analysis
# ============================================================

# Error = Measured Value - True Value
#
# Positive error: Measurement is higher than the true value
# Negative error: Measurement is lower than the true value

tool["error_nm"] = (
    tool["measured_cd_nm"]
    - tool["true_cd_nm"]
)

# Absolute error represents the magnitude of the error
tool["absolute_error_nm"] = (
    tool["error_nm"].abs()
)


# ------------------------------------------------------------
# 6.1 Measurement Error Summary by Tool
# ------------------------------------------------------------

tool_summary = (
    tool.groupby("tool_id")
    .agg(
        mean_error=("error_nm", "mean"),
        std_error=("error_nm", "std"),
        MAE=("absolute_error_nm", "mean"),
        count=("error_nm", "count")
    )
    .round(4)
)

print("\n" + "=" * 60)
print("TOOL MEASUREMENT ERROR SUMMARY")
print("=" * 60)

print(tool_summary)


# ------------------------------------------------------------
# 6.2 Measurement Error Distribution by Tool
# ------------------------------------------------------------

plt.figure(figsize=(8, 5))

sns.boxplot(
    data=tool,
    x="tool_id",
    y="error_nm"
)

# Zero represents perfect agreement with simulated true values
plt.axhline(
    0,
    color="red",
    linestyle="--",
    label="Zero Error"
)

plt.xlabel("Measurement Tool")
plt.ylabel("Measurement Error (nm)")
plt.title("Measurement Error Distribution by Tool")
plt.legend()

plt.tight_layout()

