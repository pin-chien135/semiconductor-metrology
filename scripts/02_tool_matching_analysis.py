# Objective:
# Compare measurement results from different tools
# using the same wafers.
#
# Statistical methods:
# 1. Paired measurement comparison
# 2. Paired t-test
# 3. Bland-Altman analysis
# ============================================================
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.stats import ttest_rel
from pathlib import Path

ROOT = Path.cwd().parent
DATA_DIR = ROOT / "content"
FIG_DIR = ROOT / "content" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)
tool = pd.read_csv(
    DATA_DIR / "tool_matching_data.csv"
)
sns.set_theme(style="whitegrid")

# ============================================================
# 1. Calculate Mean Measurement for Each Wafer and Tool
# ============================================================

# Each wafer is measured twice by each tool.
# Calculate the average to obtain one value per wafer per tool.
wafer_tool = (
    tool.groupby(["wafer_id", "tool_id"])
    .agg(mean_measured_cd=("measured_cd_nm", "mean"),
        true_cd=("true_cd_nm", "mean")
    )
    .reset_index()
)

print("Wafer-level Tool Matching Data:")
print(wafer_tool.head())

# ============================================================
# 2. Convert Data into Wide Format
# ============================================================

# Each row represents one wafer.
# Each column represents one measurement tool.

wide_tool = wafer_tool.pivot(
    index="wafer_id",
    columns="tool_id",
    values="mean_measured_cd"
)

print("\nPaired Tool Measurement:")
print(wide_tool.head())

# ============================================================
# 3. Calculate Paired Differences
# ============================================================
# Compare Tool B and Tool C against Tool A.
#
# Positive difference: The first tool measures a higher CD than Tool A.
# Negative difference: The first tool measures a lower CD than Tool A.

wide_tool["B_minus_A"] = (
    wide_tool["Tool_B"] - wide_tool["Tool_A"]
)
wide_tool["C_minus_A"] = (
    wide_tool["Tool_C"] - wide_tool["Tool_A"]
)
wide_tool["B_minus_C"] = (
    wide_tool["Tool_B"] - wide_tool["Tool_C"]
)

print("\nPaired Differences Summary:")
print(wide_tool[ ["B_minus_A", "C_minus_A", "B_minus_C"]
    ].describe().round(4)
)


# ============================================================
# 4. Paired t-test
# ============================================================
# H0: Mean paired difference = 0
# H1: Mean paired difference != 0

comparisons = [
    ("Tool B vs Tool A", "Tool_B", "Tool_A"),
    ("Tool C vs Tool A", "Tool_C", "Tool_A"),
    ("Tool B vs Tool C", "Tool_B", "Tool_C")
]

results = []
for name, tool_1, tool_2 in comparisons:
    t_stat, p_value = ttest_rel(
        wide_tool[tool_1],
        wide_tool[tool_2]
    )

    # Calculate average paired difference
    mean_diff = (
        wide_tool[tool_1] - wide_tool[tool_2]
    ).mean()

    results.append({
        "Comparison": name,
        "Mean Difference (nm)": mean_diff,
        "t_statistic": t_stat,
        "p_value": p_value
    })

paired_test = pd.DataFrame(results)

print("\nPaired t-test Results:")
print(paired_test.round(5))

# ============================================================
# 5. Visualize Paired Differences
# ============================================================
plt.figure(figsize=(9, 5))
sns.boxplot(data=wide_tool[
        ["B_minus_A", "C_minus_A", "B_minus_C"]
    ]
)

plt.axhline( 0,
    color="red",
    linestyle="--",
    label="No Difference"
)

plt.ylabel("Paired Measurement Difference (nm)")
plt.title("Paired Tool Matching Differences")
plt.legend()
plt.tight_layout()

plt.savefig( FIG_DIR / "06_paired_tool_differences.png", dpi=300)
plt.show()


# ============================================================
# 6. Bland-Altman Analysis
# ============================================================
# Bland-Altman analysis evaluates agreement between two measurement methods.
#
# X-axis: Average of two tools
# Y-axis: Difference between two tools
#
# Mean difference: Systematic bias
# Limits of Agreement (LoA):
# Mean difference +/- 1.96 * SD of differences

def bland_altman(data_a, data_b, label_a, label_b, filename):
    average = (data_a + data_b) / 2
    difference = data_a - data_b

    # Calculate mean bias and standard deviation
    mean_diff = difference.mean()
    sd_diff = difference.std(ddof=1)

    # Calculate 95% limits of agreement
    upper_loa = mean_diff + 1.96 * sd_diff
    lower_loa = mean_diff - 1.96 * sd_diff

    # Plot
    plt.figure(figsize=(8, 5))

    plt.scatter(average, difference, alpha=0.8)
    plt.axhline(
        mean_diff,
        color="red",
        linestyle="-",
        label=f"Mean Difference = {mean_diff:.3f}"
    )

    plt.axhline(
        upper_loa,
        color="black",
        linestyle="--",
        label=f"Upper LoA = {upper_loa:.3f}"
    )

    plt.axhline(
        lower_loa,
        color="black",
        linestyle="--",
        label=f"Lower LoA = {lower_loa:.3f}"
    )

    plt.xlabel("Average CD of Two Tools (nm)")
    plt.ylabel("Difference Between Tools (nm)")
    plt.title(f"Bland-Altman: {label_a} vs {label_b}"
    )

    plt.legend()
    plt.tight_layout()
    plt.savefig(FIG_DIR / filename, dpi=300)
    plt.show()

    return {
        "Comparison": f"{label_a} vs {label_b}",
        "Mean Difference": mean_diff,
        "SD Difference": sd_diff,
        "Upper LoA": upper_loa,
        "Lower LoA": lower_loa
    }


# Compare Tool B with Tool A
ba_ba = bland_altman(
    wide_tool["Tool_B"],
    wide_tool["Tool_A"],
    "Tool B",
    "Tool A",
    "07_bland_altman_B_A.png"
)

# Compare Tool C with Tool A
ba_ca = bland_altman(
    wide_tool["Tool_C"],
    wide_tool["Tool_A"],
    "Tool C",
    "Tool A",
    "08_bland_altman_C_A.png"
)

print("\nBland-Altman Summary:")
print(pd.DataFrame([ba_ba, ba_ca]).round(4))

# ============================================================
# 7. Export Results
# ============================================================

wide_tool.to_csv(
    DATA_DIR / "paired_tool_data.csv"
)

paired_test.to_csv(
    DATA_DIR / "paired_tool_ttest.csv",
    index=False
)

