# Method: Crossed ANOVA Gauge R&R
#
# Experimental Design:
# 10 Parts (Wafers)
# 3 Operators
# 2 Repeated Measurements
# 1 Measurement Tool
#  Total observations = 10 * 3 * 2 = 60
#
# Objective:
# 1. Evaluate Repeatability
# 2. Evaluate Reproducibility
# 3. Evaluate Part-to-Part Variation
# 4. Calculate Total Gauge R&R
# ============================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
from scipy.stats import f

# ============================================================
# 1. Define Project Paths
# ============================================================
ROOT = Path.cwd().parent

DATA_DIR = ROOT / "content"
FIG_DIR = ROOT / "content" / "figures"
RESULT_DIR = ROOT / "content" / "results"
FIG_DIR.mkdir(parents=True, exist_ok=True)
RESULT_DIR.mkdir(parents=True, exist_ok=True)

# Load MSA dataset
msa = pd.read_csv(DATA_DIR / "msa_data.csv")
sns.set_theme(style="whitegrid")

# ============================================================
# 2. Data Validation
# ============================================================

print("=" * 60)
print("MSA DATA VALIDATION")
print("=" * 60)

required_columns = [
    "wafer_id",
    "operator_id",
    "repeat",
    "measured_cd_nm"
]

# Check required columns
missing_columns = [
    col for col in required_columns
    if col not in msa.columns
]

if missing_columns:
    raise ValueError(
        f"Missing required columns: {missing_columns}"
    )

# Check missing values
if msa[required_columns].isnull().any().any():
    raise ValueError("Missing values found in MSA data.")

# Check duplicate measurement combinations
if msa.duplicated(
    subset=["wafer_id", "operator_id", "repeat"]
).any():
    raise ValueError(
        "Duplicate wafer/operator/repeat combinations found."
    )

# Get experimental design dimensions
n_parts = msa["wafer_id"].nunique()
n_operators = msa["operator_id"].nunique()

# Every wafer-operator combination must have the same
# number of repeated measurements.
replicate_counts = (
    msa.groupby(["wafer_id", "operator_id"])
    .size()
)

if replicate_counts.nunique() != 1:
    raise ValueError(
        "Unbalanced design: replicate counts are not equal."
    )

n_repeats = int(replicate_counts.iloc[0])

expected_records = (
    n_parts * n_operators * n_repeats
)

if len(msa) != expected_records:
    raise ValueError(
        "Unexpected number of observations."
    )

# This script assumes one measurement tool.
if "tool_id" in msa.columns:
    if msa["tool_id"].nunique() != 1:
        raise ValueError(
            "Crossed ANOVA model assumes one measurement tool."
        )

print(f"Number of Parts: {n_parts}")
print(f"Number of Operators: {n_operators}")
print(f"Repeated Measurements: {n_repeats}")
print(f"Total Observations: {len(msa)}")

print("\nData validation passed.")

# ============================================================
