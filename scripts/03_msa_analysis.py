# ============================================================
# 4. Two-Way ANOVA Calculations
# ============================================================

# IMPORTANT:
# Use measured_cd_nm only.
#
# true_cd_nm is simulated ground truth.
# It is NOT included in Gauge R&R variance calculations.


# ------------------------------------------------------------
# 4.1 Calculate Grand Mean and Group Means
# ------------------------------------------------------------

grand_mean = msa["measured_cd_nm"].mean()

part_means = (
    msa.groupby("wafer_id")["measured_cd_nm"]
    .mean()
)

operator_means = (
    msa.groupby("operator_id")["measured_cd_nm"]
    .mean()
)

cell_means = (
    msa.groupby(["wafer_id", "operator_id"])
    ["measured_cd_nm"]
    .mean()
)


# ------------------------------------------------------------
# 4.2 Sum of Squares
# ------------------------------------------------------------

# Part-to-Part Sum of Squares
SS_part = (
    n_operators * n_repeats
    * ((part_means - grand_mean) ** 2).sum()
)

# Operator Sum of Squares
SS_operator = (
    n_parts * n_repeats
    * ((operator_means - grand_mean) ** 2).sum()
)

# Operator x Part Interaction Sum of Squares
SS_interaction = 0.0

for (part, operator), cell_mean in cell_means.items():

    interaction_effect = (
        cell_mean
        - part_means.loc[part]
        - operator_means.loc[operator]
        + grand_mean
    )

    SS_interaction += (
        n_repeats * interaction_effect ** 2
    )


# Repeatability / Residual Sum of Squares

# Calculate the corresponding cell mean for each observation.
msa["cell_mean"] = (
    msa.groupby(["wafer_id", "operator_id"])
    ["measured_cd_nm"]
    .transform("mean")
)

msa["residual"] = (
    msa["measured_cd_nm"] - msa["cell_mean"]
)

SS_repeatability = (
    msa["residual"] ** 2
).sum()


# ------------------------------------------------------------
# 4.3 Degrees of Freedom
# ------------------------------------------------------------

df_part = n_parts - 1

df_operator = n_operators - 1

df_interaction = (
    (n_parts - 1) * (n_operators - 1)
)

df_repeatability = (
    n_parts * n_operators * (n_repeats - 1)
)

# Total degrees of freedom
df_total = len(msa) - 1


# ------------------------------------------------------------
# 4.4 Mean Squares
# ------------------------------------------------------------

MS_part = SS_part / df_part
MS_operator = SS_operator / df_operator

MS_interaction = ( SS_interaction / df_interaction)
MS_repeatability = ( SS_repeatability / df_repeatability)

# ============================================================
# 5. ANOVA Table
# ============================================================

# F-tests for the crossed random-effects model:
#
# Part effect: MS_part / MS_interaction
# Operator effect: MS_operator / MS_interaction
# Interaction: MS_interaction / MS_repeatability

anova_rows = [
    {
        "Source": "Part",
        "SS": SS_part,
        "DF": df_part,
        "MS": MS_part,
        "F": MS_part / MS_interaction,
        "p_value": f.sf(
            MS_part / MS_interaction,
            df_part,
            df_interaction
        )
    },
    {
        "Source": "Operator",
        "SS": SS_operator,
        "DF": df_operator,
        "MS": MS_operator,
        "F": MS_operator / MS_interaction,
        "p_value": f.sf(
            MS_operator / MS_interaction,
            df_operator,
            df_interaction
        )
    },
    {
        "Source": "Part x Operator",
        "SS": SS_interaction,
        "DF": df_interaction,
        "MS": MS_interaction,
        "F": MS_interaction / MS_repeatability,
        "p_value": f.sf(
            MS_interaction / MS_repeatability,
            df_interaction,
            df_repeatability
        )
    },
    {
        "Source": "Repeatability",
        "SS": SS_repeatability,
        "DF": df_repeatability,
        "MS": MS_repeatability,
        "F": np.nan,
        "p_value": np.nan
    }
]

anova_table = pd.DataFrame(anova_rows)

print("\n" + "=" * 60)
print("CROSSED ANOVA TABLE")
print("=" * 60)

print(
    anova_table.to_string(
        index=False,
        float_format=lambda x: f"{x:.6f}"
    )
)

# ============================================================
# 6. Variance Component Estimation
# ============================================================

# Variance components are estimated from Mean Squares.
#
# Negative estimates can occur due to sampling variation.
# For this introductory Gauge R&R summary, negative
# components are truncated to zero.
#
# The untruncated estimates are retained for transparency.


# ------------------------------------------------------------
# 6.1 Raw Variance Components
# ------------------------------------------------------------

var_repeat_raw = MS_repeatability

var_interaction_raw = (
    MS_interaction - MS_repeatability
) / n_repeats

var_operator_raw = (
    MS_operator - MS_interaction
) / (n_parts * n_repeats)

var_part_raw = (
    MS_part - MS_interaction
) / (n_operators * n_repeats)


# ------------------------------------------------------------
# 6.2 Truncate Negative Estimates
# ------------------------------------------------------------

var_repeat = max(0, var_repeat_raw)

var_interaction = max(0, var_interaction_raw)

var_operator = max(0, var_operator_raw)

var_part = max(0, var_part_raw)


# ------------------------------------------------------------
# 6.3 Reproducibility and Total Gage R&R
# ------------------------------------------------------------

# Reproducibility includes:
# Operator variation + Operator x Part interaction.

var_reproducibility = (
    var_operator + var_interaction
)

# Total Gage R&R:
# Repeatability + Reproducibility

var_grr = (
    var_repeat + var_reproducibility
)

# Total observed variation:
# Gage R&R + Part-to-Part variation

var_total = var_grr + var_part

# ============================================================
# 7. Gauge R&R Summary
# ============================================================

variance_components = {
    "Repeatability": var_repeat,
    "Operator": var_operator,
    "Part x Operator": var_interaction,
    "Reproducibility": var_reproducibility,
    "Total Gage R&R": var_grr,
    "Part-to-Part": var_part,
    "Total Variation": var_total
}

grr_summary = pd.DataFrame(
    list(variance_components.items()),
    columns=["Source", "Variance"]
)

# Standard deviation for each component
grr_summary["StdDev"] = np.sqrt(
    grr_summary["Variance"]
)

# Study Variation = 6 * Standard Deviation
grr_summary["Study Variation (6SD)"] = (
    6 * grr_summary["StdDev"]
)

# Percentage Contribution
grr_summary["% Contribution"] = (
    grr_summary["Variance"]
    / var_total * 100
    if var_total > 0
    else np.nan
)

# Percentage Study Variation
grr_summary["% Study Variation"] = (
    grr_summary["StdDev"]
    / np.sqrt(var_total) * 100
    if var_total > 0
    else np.nan
)

print("\n" + "=" * 60)
print("GAUGE R&R VARIANCE COMPONENTS")
print("=" * 60)

print(
    grr_summary.to_string(
        index=False,
        float_format=lambda x: f"{x:.4f}"
    )
)

# ============================================================
# 8. Number of Distinct Categories (ndc)
# ============================================================

# ndc estimates how many distinct groups of parts
# the measurement system can reliably distinguish.
#
# Formula:
# ndc = 1.41 * sqrt(Part-to-Part Variance / Gage R&R Variance)

if var_grr > 0:

    ndc_raw = (
        1.41 * np.sqrt(var_part / var_grr)
    )

    ndc = int(np.floor(ndc_raw))

else:

    ndc_raw = np.inf
    ndc = np.inf

print("\n" + "=" * 60)
print("NUMBER OF DISTINCT CATEGORIES")
print("=" * 60)

print(f"ndc (raw): {ndc_raw:.4f}")
print(f"ndc (rounded down): {ndc}")

