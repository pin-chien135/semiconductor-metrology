from scipy.stats import f

# Crossed Random-Effects ANOVA
F_part = ms_part / ms_interaction
F_operator = ms_operator / ms_interaction
F_interaction = ms_interaction / ms_repeat

p_part = f.sf(F_part, df_part, df_interaction)
p_operator = f.sf(F_operator, df_operator, df_interaction)
p_interaction = f.sf(
    F_interaction,
    df_interaction,
    df_repeat
)

corrected_anova = pd.DataFrame({
    "Source": ["Part", "Operator", "Part x Operator"],
    "F": [F_part, F_operator, F_interaction],
    "p_value": [p_part, p_operator, p_interaction]
})

print("\n========== Corrected Crossed ANOVA ==========")
print(corrected_anova.to_string(index=False))

