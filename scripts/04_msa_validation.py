from pathlib import Path
from itertools import combinations
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats
from statsmodels.formula.api import ols
from statsmodels.stats.anova import anova_lm


# ==================================================
# 1. 路徑與讀取
# ==================================================

ROOT = Path.cwd().parent
DATA_DIR = ROOT / "content"
FIG_DIR = ROOT / "content" / "figures"
RESULT_DIR = ROOT / "content" / "results"

FIG_DIR.mkdir(parents=True, exist_ok=True)
RESULT_DIR.mkdir(parents=True, exist_ok=True)

df = pd.read_csv(DATA_DIR / "msa_data.csv")

required_columns = [
    "wafer_id", "operator_id", "measured_cd_nm"
]
df = df[required_columns]

df.head()

# ==================================================
# 2. Crossed ANOVA：
# ==================================================
model = ols(
    "measured_cd_nm ~ C(wafer_id) * C(operator_id)",
    data=df ).fit()

anova_table = anova_lm(model, typ=2)

print("\n========== Crossed ANOVA ==========")
print(anova_table)

anova_table.to_csv(
    RESULT_DIR / "msa_anova_table.csv"
)

# SS、DF、MS
ss_part = anova_table.loc["C(wafer_id)", "sum_sq"]
df_part = anova_table.loc["C(wafer_id)", "df"]

ss_operator = anova_table.loc["C(operator_id)", "sum_sq"]
df_operator = anova_table.loc["C(operator_id)", "df"]

ss_interaction = anova_table.loc[
    "C(wafer_id):C(operator_id)", "sum_sq"
]
df_interaction = anova_table.loc[
    "C(wafer_id):C(operator_id)", "df"
]

ss_repeat = anova_table.loc["Residual", "sum_sq"]
df_repeat = anova_table.loc["Residual", "df"]

ms_part = ss_part / df_part
ms_operator = ss_operator / df_operator
ms_interaction = ss_interaction / df_interaction
ms_repeat = ss_repeat / df_repeat

print("\n========== Mean Squares ==========")
print(f"MS Part        : {ms_part:.6f}")
print(f"MS Operator    : {ms_operator:.6f}")
print(f"MS Interaction : {ms_interaction:.6f}")
print(f"MS Repeat      : {ms_repeat:.6f}")

# ==================================================
# 3. Interaction Pooling
# ==================================================

n_parts = df["wafer_id"].nunique()
n_operators = df["operator_id"].nunique()

# 每個 Part × Operator 組合的重複測量次數
repeats_per_cell = (
    df.groupby(["wafer_id", "operator_id"])
    .size()
)

if repeats_per_cell.nunique() != 1:
    raise ValueError(
        "目前資料不是平衡設計，不能直接使用這份簡化的 pooling 計算。"
    )

n_repeats = int(repeats_per_cell.iloc[0])

# 將 Interaction SS 與 Repeatability SS 合併
ss_pooled_error = ss_interaction + ss_repeat
df_pooled_error = df_interaction + df_repeat
ms_pooled_error = ss_pooled_error / df_pooled_error

# Pooled model 的變異分量
var_repeat_pooled = ms_pooled_error

var_operator_pooled = max(
    0,
    (ms_operator - ms_pooled_error)
    / (n_parts * n_repeats)
)

var_part_pooled = max(
    0,
    (ms_part - ms_pooled_error)
    / (n_operators * n_repeats)
)

var_reproducibility_pooled = var_operator_pooled

var_grr_pooled = (
    var_repeat_pooled
    + var_reproducibility_pooled
)

var_total_pooled = (
    var_grr_pooled
    + var_part_pooled
)

sd_grr_pooled = np.sqrt(var_grr_pooled)
sd_total_pooled = np.sqrt(var_total_pooled)

study_variation_grr = 6 * sd_grr_pooled
study_variation_total = 6 * sd_total_pooled

pct_contribution_grr = (
    var_grr_pooled / var_total_pooled * 100
)

pct_study_variation_grr = (
    sd_grr_pooled / sd_total_pooled * 100
)

ndc_pooled = np.floor(
    1.41 * np.sqrt(var_part_pooled / var_grr_pooled)
)

pooled_results = pd.DataFrame({
    "Metric": [
        "Repeatability Variance",
        "Operator Variance",
        "Reproducibility Variance",
        "Total GRR Variance",
        "Part-to-Part Variance",
        "Total Variance",
        "GRR Study Variation (6SD)",
        "Total Study Variation (6SD)",
        "GRR % Contribution",
        "GRR % Study Variation",
        "ndc"
    ],
    "Value": [
        var_repeat_pooled,
        var_operator_pooled,
        var_reproducibility_pooled,
        var_grr_pooled,
        var_part_pooled,
        var_total_pooled,
        study_variation_grr,
        study_variation_total,
        pct_contribution_grr,
        pct_study_variation_grr,
        ndc_pooled
    ]
})

print("\n========== Interaction Pooling ==========")
print(pooled_results.to_string(index=False))

pooled_results.to_csv(
    RESULT_DIR / "msa_pooled_results.csv",
    index=False
)

# ==================================================
# 4. Operator Post-hoc：配對比較
# ==================================================
# 先將同一個 Wafer、同一個 Operator 的兩次量測取平均
cell_means = (
    df.groupby(["wafer_id", "operator_id"])["measured_cd_nm"]
    .mean()
    .unstack("operator_id")
)

print("\n========== Operator Cell Means ==========")
print(cell_means)

operators = list(cell_means.columns)

pairwise_results = []

for op1, op2 in combinations(operators, 2):

    # 同一批 Wafer 由兩位 Operator 量測
    # 使用 paired t-test 保留 Wafer 配對關係
    t_stat, p_value = stats.ttest_rel(
        cell_means[op1],
        cell_means[op2]
    )

    mean_difference = (
        cell_means[op1] - cell_means[op2]
    ).mean()

    pairwise_results.append({
        "Operator_1": op1,
        "Operator_2": op2,
        "Mean_Difference_nm": mean_difference,
        "t_statistic": t_stat,
        "p_raw": p_value
    })

pairwise_df = pd.DataFrame(pairwise_results)


# Holm correction：修正多重比較
p_values = pairwise_df["p_raw"].to_numpy()
m = len(p_values)

order = np.argsort(p_values)
adjusted = np.empty(m)

for rank, idx in enumerate(order):
    adjusted[idx] = min(
        1.0,
        (m - rank) * p_values[idx]
    )

# 確保調整後 p-value 單調不遞減
for i in range(1, m):
    adjusted[order[i]] = max(
        adjusted[order[i]],
        adjusted[order[i - 1]]
    )

pairwise_df["p_holm"] = adjusted
pairwise_df["Significant"] = (
    pairwise_df["p_holm"] < 0.05
)

print("\n========== Operator Paired Comparisons ==========")
print(pairwise_df.to_string(index=False))

pairwise_df.to_csv(
    RESULT_DIR / "msa_operator_posthoc.csv",
    index=False
)

